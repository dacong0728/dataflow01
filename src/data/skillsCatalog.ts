export function createNodeFromSkill(
  skill: SkillDefinition,
  overrides: Partial<PipelineNode> = {},
): PipelineNode {
  const uniqueSuffix = Math.random().toString(36).slice(2, 7);
  return {
    instanceId: `node-${skill.id}-${uniqueSuffix}`,
    skillId: skill.id,
    name: skill.name,
    displayName: skill.displayName,
    track: skill.track,
    stage: skill.stage,
    maturity: skill.maturity,
    assignedSessionId: skill.defaultSessionId,
    executionStatus: 'idle',
    prompt: '',
    outputSummary: '',
    outputContent: '',
    outputFormat: skill.defaultFormat,
    handoffLabel: skill.outputArtifactType,
    updatedAt: '尚未执行',
    updatedBy: '编排待命',
    ...overrides,
  };
}

function getSkillOrThrow(id: string): SkillDefinition {
  const found = SKILLS_CATALOG.find((s) => s.id === id);
  if (!found) {
    throw new Error(`Missing skill definition: ${id}`);
  }
  return found;
}

